<p>如果要編碼的位元組數不能被3整除，最後會多出1個或2個位元組，那麼可以使用下面的方法進行處理：先使用0位元組值在末尾補足，使其能夠被3整除，然後再進行Base64的編碼。在編碼後的Base64文字後加上一個或兩個<code>=</code>號，代表補足的位元組數。也就是說，當最後剩餘兩個八位(待補足)位元組（2個byte）時，最後一個6位的Base64位元組塊有四位是0值，最後附加上兩個等號；如果最後剩餘一個八位(待補足)位元組（1個byte）時，最後一個6位的base位元組塊有兩位是0值，最後附加一個等號。
